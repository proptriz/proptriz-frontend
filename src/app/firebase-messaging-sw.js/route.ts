// Serves /firebase-messaging-sw.js with the real Firebase web settings.
//
// A file in /public cannot read environment variables, so the service worker
// is generated here from the same NEXT_PUBLIC_FIREBASE_* values the app uses.
// (These web settings are public identifiers, not secrets.)

import { version as firebaseVersion } from 'firebase/package.json';

export const dynamic = 'force-static';

const firebaseConfig = {
  apiKey:            process.env.NEXT_PUBLIC_FIREBASE_API_KEY,
  authDomain:        process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN,
  projectId:         process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID,
  storageBucket:     process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_SENDER_ID,
  appId:             process.env.NEXT_PUBLIC_FIREBASE_APP_ID,
};

const isConfigured = Boolean(
  firebaseConfig.apiKey && firebaseConfig.projectId && firebaseConfig.messagingSenderId && firebaseConfig.appId
);

function buildServiceWorker(): string {
  if (!isConfigured) {
    // No Firebase settings in this build: ship a worker that does nothing
    // rather than one that starts Firebase with placeholder values.
    return `// Push is not configured for this build.\n`;
  }

  return `// Generated by src/app/firebase-messaging-sw.js/route.ts. Do not edit.
importScripts("https://www.gstatic.com/firebasejs/${firebaseVersion}/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/${firebaseVersion}/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(firebaseConfig)});

const messaging = firebase.messaging();
const ICON = "/android-chrome-192x192.png";
const BADGE = "/favicon-32x32.png";

// Only links on this site may be opened from a notification.
function safeUrl(url) {
  try {
    const target = new URL(url || "/", self.location.origin);
    return target.origin === self.location.origin ? target.href : self.location.origin + "/";
  } catch (e) {
    return self.location.origin + "/";
  }
}

// Background messages. When the message carries a "notification" block the
// Firebase SDK shows it by itself, so only data-only messages are shown here
// (showing both would produce two notifications).
messaging.onBackgroundMessage((payload) => {
  if (payload.notification) return;

  const data = payload.data || {};
  if (!data.title) return;

  return self.registration.showNotification(data.title, {
    body: data.body || "",
    icon: ICON,
    badge: BADGE,
    image: data.imageUrl,
    data: { url: safeUrl(data.url) },
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();

  const data = event.notification.data || {};
  const url = safeUrl(data.url || (data.FCM_MSG && data.FCM_MSG.data && data.FCM_MSG.data.url));

  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((windowClients) => {
      for (const client of windowClients) {
        if (new URL(client.url).origin === self.location.origin && "focus" in client) {
          return client.focus().then((focused) => (focused && "navigate" in focused ? focused.navigate(url) : undefined));
        }
      }
      if (clients.openWindow) return clients.openWindow(url);
    })
  );
});
`;
}

export function GET() {
  return new Response(buildServiceWorker(), {
    headers: {
      'Content-Type': 'application/javascript; charset=utf-8',
      // Browsers must always re-check the worker so config changes roll out.
      'Cache-Control': 'public, max-age=0, must-revalidate',
      'Service-Worker-Allowed': '/',
    },
  });
}
